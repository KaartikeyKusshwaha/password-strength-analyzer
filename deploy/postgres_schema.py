"""Prepare an empty PostgreSQL schema from this release's SQLite schema only.

This does not read an application database or migrate accounts. Apply it only
to a dedicated empty target; account migration is a separate validated step.
"""
import argparse
from contextlib import closing
from pathlib import Path
import re
import sqlite3
import sys
import tempfile

ROOT=Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:sys.path.insert(0,str(ROOT))
from backend.store import Store,SCHEMA_VERSION


def quoted(value):
    return '"'+value.replace('"','""')+'"'


def prepare(schema='sentinelops'):
    if not re.fullmatch('[a-z][a-z0-9_]{0,62}',schema) or schema in {'public','pg_catalog','information_schema'}:raise ValueError('Use a simple dedicated schema name.')
    statements=['BEGIN;',f'CREATE SCHEMA {quoted(schema)};',f'SET LOCAL search_path TO {quoted(schema)};']
    inventory={}
    with tempfile.TemporaryDirectory(prefix='sentinelops-empty-schema-') as temporary:
        path=Path(temporary)/'empty.db'
        Store(path)
        with closing(sqlite3.connect(path)) as c:
            tables=c.execute("SELECT name,sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name").fetchall()
            for name,source in tables:
                fields=[];columns=c.execute('PRAGMA table_info('+quoted(name)+')').fetchall()
                inventory[name]=[row[1] for row in columns]
                primary=[row[1] for row in sorted(columns,key=lambda row:row[5]) if row[5]]
                for _,column,kind,required,default,is_primary in columns:
                    identity=bool(is_primary and kind.upper()=='INTEGER' and len(primary)==1)
                    data_type={'TEXT':'TEXT','INTEGER':'BIGINT','REAL':'DOUBLE PRECISION','BLOB':'BYTEA'}.get(kind.upper())
                    if data_type is None:raise ValueError('Unsupported source column type.')
                    field=quoted(column)+' '+data_type
                    if identity:field+=' GENERATED BY DEFAULT AS IDENTITY'
                    elif default is not None:field+=' DEFAULT '+default
                    if required:field+=' NOT NULL'
                    fields.append(field)
                if primary:fields.append('PRIMARY KEY ('+','.join(map(quoted,primary))+')')
                # SQLite insertion order is used for deterministic evidence and
                # membership ordering. Keep it explicit rather than using ctid.
                if name in {'entities','members'}:fields.append('"_sentinel_order" BIGINT GENERATED ALWAYS AS IDENTITY')
                statements.append(f'CREATE TABLE {quoted(name)} ('+','.join(fields)+');')
                for index in c.execute('PRAGMA index_list('+quoted(name)+')').fetchall():
                    if index[3]=='pk':continue
                    parts=c.execute('PRAGMA index_info('+quoted(index[1])+')').fetchall()
                    if not parts or any(row[2] is None for row in parts):raise ValueError('Expression index needs an explicit PostgreSQL migration.')
                    predicate=''
                    if index[4]:
                        sql=c.execute('SELECT sql FROM sqlite_master WHERE type=\'index\' AND name=?',(index[1],)).fetchone()[0]
                        raw=re.split(r'\bWHERE\b',sql,maxsplit=1,flags=re.I)[1].strip()
                        if raw not in {'is_default=1','revoked_at IS NULL'}:raise ValueError('Partial index needs an explicit PostgreSQL migration.')
                        predicate=' WHERE '+raw
                    index_name=index[1] if not index[1].startswith('sqlite_') else name+'__unique_'+str(index[0])
                    statements.append('CREATE '+('UNIQUE ' if index[2] else '')+'INDEX '+quoted(index_name)+' ON '+quoted(name)+' ('+','.join(quoted(row[2]) for row in parts)+')'+predicate+';')
    for version in range(1,SCHEMA_VERSION+1):
        statements.append(f"INSERT INTO schema_migrations(version,applied_at) VALUES({version},CURRENT_TIMESTAMP::text);")
    statements.append('COMMIT;')
    return '\n'.join(statements)+'\n',inventory


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',required=True)
    parser.add_argument('--schema',default='sentinelops')
    args=parser.parse_args()
    sql,_=prepare(args.schema)
    with Path(args.output).open('x',encoding='utf-8') as handle:handle.write(sql)
    print('Empty-schema preparation complete. No application records were read or migrated.')


if __name__=='__main__':main()
